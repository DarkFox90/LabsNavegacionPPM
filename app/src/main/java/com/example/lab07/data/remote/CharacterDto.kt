package com.example.lab07.data.remote

import kotlinx.serialization.Serializable

@Serializable
data class CharacterDto(
    val id: Int,
    val name: String,
    val status: String,
    val species: String,
    val gender: String,
    val image: String
)

@Serializable
data class CharacterResponseDto(
    val results: List<CharacterDto>
)